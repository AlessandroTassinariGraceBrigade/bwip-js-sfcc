// build-gs1-format.js
// Generates dist/gs1-format.js : a standalone helper that converts a raw
// concatenated GS1 element string into the (AI)value bracketed form expected
// by bcid "gs1-128". The list of valid AIs and the fixed-length prefixes are
// extracted from ../src/bwipp.js so they always match the encoder.
'use strict';
const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const HERE = __dirname;
const lines = fs.readFileSync(path.join(REPO, 'src', 'bwipp.js'), 'utf8').split('\n');

// --- extract the full valid-AI set from the gs1syntax Map ---
const end = lines.findIndex((l) => l.includes('$_.gs1syntax = _Oq'));
let start = end;
while (start > 0 && !/new Map\(\[/.test(lines[start])) start--;
const ais = [];
for (let i = start; i <= end; i++) {
    const m = lines[i].match(/\["([0-9]{2,4})",/g);
    if (m) m.forEach((x) => ais.push(x.match(/[0-9]{2,4}/)[0]));
}
const AIS = Array.from(new Set(ais)).sort();

// --- extract the fixed-length AI prefixes (aifixed) ---
const fixedLine = lines.find((l) => l.includes('"00", "01", "02", "03", "04"'));
const fixedPrefixes = (fixedLine.match(/"([0-9]{2})"/g) || []).map((s) => s.replace(/"/g, ''));
console.error('AIs: ' + AIS.length + ' ; fixed prefixes: ' + fixedPrefixes.join(','));

// Total element length (AI digits + data digits) and AI digit-length per prefix.
// Derived from the GS1 General Specifications predefined-length table.
const FIXED = {
    '00': { ai: 2, total: 20 }, '01': { ai: 2, total: 16 }, '02': { ai: 2, total: 16 },
    '03': { ai: 2, total: 16 }, '04': { ai: 2, total: 18 },
    '11': { ai: 2, total: 8 }, '12': { ai: 2, total: 8 }, '13': { ai: 2, total: 8 },
    '14': { ai: 2, total: 8 }, '15': { ai: 2, total: 8 }, '16': { ai: 2, total: 8 },
    '17': { ai: 2, total: 8 }, '18': { ai: 2, total: 8 }, '19': { ai: 2, total: 8 },
    '20': { ai: 2, total: 4 },
    '31': { ai: 4, total: 10 }, '32': { ai: 4, total: 10 }, '33': { ai: 4, total: 10 },
    '34': { ai: 4, total: 10 }, '35': { ai: 4, total: 10 }, '36': { ai: 4, total: 10 },
    '41': { ai: 3, total: 16 },
};
// sanity: every extracted fixed prefix must be described above
for (const p of fixedPrefixes) {
    if (!FIXED[p]) throw new Error('missing FIXED entry for prefix ' + p);
}

const tpl = `// =====================================================================
// gs1-format.js  (companion to gs1-128-svg.js)
//
// Converts a RAW concatenated GS1 element string into the "(AI)value"
// bracketed form required by bcid "gs1-128".
//
//   gs1Format("0102...(digits)")  ->  "(01)...(21)..."
//
// Rules:
//   * Fixed-length AIs (00,01,02,03,04,11-20,31-36,41) are split by their
//     predefined length, so NO separators are needed between them.
//   * Variable-length AIs are read until the next FNC1/GS separator
//     (ASCII 0x1d, or the textual markers "^FNC1"/"^GS") or the end of the
//     string. A variable-length field that is NOT the last field MUST be
//     followed by a separator, otherwise it would swallow the following AIs.
//
// RhinoJS / SFCC compatible (ES5). Auto-generated by build-gs1-format.js.
// =====================================================================
(function (root, factory) {
    if (typeof module !== 'undefined' && module.exports) { module.exports = factory(); }
    else if (typeof exports !== 'undefined') { exports.gs1Format = factory(); }
    else if (root) { root.gs1Format = factory(); }
})(typeof self !== 'undefined' ? self : this, function () {
    'use strict';

    var AIS = ${JSON.stringify(AIS.join(' '))}.split(' ');
    var AISET = {};
    for (var i = 0; i < AIS.length; i++) { AISET[AIS[i]] = true; }

    // prefix (first two AI digits) -> { ai: <AI digit count>, total: <AI+data> }
    var FIXED = ${JSON.stringify(FIXED, null, 8).replace(/\n/g, '\n    ')};

    function isSep(ch) {
        return ch === '\\x1d' || ch === '\\x1e' || ch === '\\x1f';
    }

    function matchAI(s, pos) {
        for (var len = 4; len >= 2; len--) {
            var code = s.substr(pos, len);
            if (code.length === len && AISET[code]) { return code; }
        }
        return null;
    }

    // gs1Format(input) -> "(AI)value(AI)value..."
    function gs1Format(input) {
        var s = String(input == null ? '' : input)
            .replace(/\\^FNC1/g, '\\x1d')
            .replace(/\\^GS/g, '\\x1d')
            .replace(/^\\x1d+/, '');       // drop any leading FNC1 start marker

        if (s.charAt(0) === '(') { return s; }   // already bracketed

        var out = '';
        var pos = 0;
        while (pos < s.length) {
            while (pos < s.length && isSep(s.charAt(pos))) { pos++; }
            if (pos >= s.length) { break; }

            var ai = matchAI(s, pos);
            if (!ai) {
                throw new Error('gs1Format: no valid GS1 AI found at position ' +
                    pos + ' (near "' + s.substr(pos, 4) + '")');
            }

            var fixed = FIXED[ai.substr(0, 2)];
            var value;
            if (fixed) {
                value = s.substr(pos + fixed.ai, fixed.total - fixed.ai);
                pos += fixed.total;
            } else {
                var startv = pos + ai.length;
                var endv = startv;
                while (endv < s.length && !isSep(s.charAt(endv))) { endv++; }
                value = s.substring(startv, endv);
                pos = endv;
            }
            out += '(' + ai + ')' + value;
        }
        return out;
    }

    return gs1Format;
});
`;

fs.mkdirSync(path.join(HERE, 'dist'), { recursive: true });
fs.writeFileSync(path.join(HERE, 'dist', 'gs1-format.js'), tpl);
console.error('wrote dist/gs1-format.js');
